/* Lane FOGGRID22A (2026-11-07): the CPU twin of MODULES1 part 22's lamp injection into the fog grid (the LampVol stage,
 * notes/fogresearch1/fog_grid.md 2.1-2.6). Header only, std only, no Qt, no GL. The shader half (cell_volair.frag
 * stage 4) mirrors each function here line for line; a GLSL function carries "MIRROR airlampinjmath.h <name>".
 * Unit: tests/features/air/airlampinj (G1-G8 and their reds).
 *
 * What one froxel does a frame:
 *   1. its sample point: the froxel's column + slice, jittered by our spatiotemporal blue-noise mask
 *      (res/air/stbn_scalar_128x128x64.r8, ours, generated by the published void-and-cluster method), maskPoint;
 *   2. the lamps of its cluster at that point: lightRadial x spotCone x intensity x T(P -> lamp) x pi p(cos), and the
 *      visibility ONLY for shadow-casting LIGHs (non-shadow lamps: V = 1, a smooth glow), injectPoint;
 *   3. the steady part blended with the reprojected history, a = max(0.1 still / 0.2 moving, 1 / (N + 1)) with N the
 *      samples the history holds (a running mean first, then the EMA; N rides in the history's spare channel); rejected (a = 1, history
 *      dropped, 4 samples instead of 1) on a cut, outside the previous frustum, a depth-skipped history tap, or a changed
 *      light-set hash of its cluster (lamp set, a steady lamp's intensity bits, a mover's position bits); the
 *      flickering lamps go to a second term written fresh every frame and never blended, LampVolume::step;
 *   4. NaN / Inf -> 0 and a clamp to 65504 (half float), sanitize.
 * The old path (stage-1 loop airRest: the 4-midpoint stretch along the column's ray, visibility at the froxel middle
 * for EVERY lamp) is oldPath, the red WW_CELL_AIR_LAMPS_RED=pixel.
 *
 * Twin simplifications (stated, shared by both paths): one colour channel; a homogeneous medium (T = exp(-sigma d));
 * one Henyey-Greenstein lobe for the phase; binary point visibility against boxes for both the cube and the atlas. */


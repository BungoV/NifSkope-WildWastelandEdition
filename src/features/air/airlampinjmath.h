// ------------------------------------------------------------------ reds (WW_CELL_AIR_LAMPS_RED and the unit's own)
struct Red
{
	bool pixel = false;        // the old stage-1 loop (WW_CELL_AIR_LAMPS_RED=pixel)
	bool nsatlas = false;      // non-shadow lamps take visibility too (today's atlas for every lamp)
	bool noshadow = false;     // shadow casters unshadowed
	bool white = false;        // white noise instead of the mask
	bool nosethash = false;    // the light-set part of the cluster hash dropped
	bool nomovehash = false;   // the movers' position bits not hashed
	bool nofrustum = false;    // rule 1 (cut, outside the previous frustum) off
	bool noskip = false;       // rule 2 (a depth-skipped history tap) off
	bool blendflicker = false; // flicker lamps blended into the history with the steady ones
	bool nonan = false;        // no NaN / Inf guard, no clamp
	bool onemiss = false;      // a history miss takes 1 sample instead of 4
	bool noramp = false;       // fixed a, no history-length ramp
	bool nochord = false;      // every lamp at the froxel's one sample point (before MODULES1 R5A-4; WW_CELL_AIR_LAMPS_RED=nochord)
};

// ------------------------------------------------------------------ geometry
struct Camera
{
	V3 pos, right = V3( 1, 0, 0 ), up = V3( 0, 1, 0 ), fwd = V3( 0, 0, 1 );
	float tanX = 1.0f, tanY = 1.0f;   // half-angle tangents
	bool operator==( const Camera & o ) const
	{
		auto eq = []( V3 a, V3 b ) { return a.x == b.x && a.y == b.y && a.z == b.z; };
		return eq( pos, o.pos ) && eq( right, o.right ) && eq( up, o.up ) && eq( fwd, o.fwd ) && tanX == o.tanX && tanY == o.tanY;
	}
};

struct Grid
{
	int cols = 32, rows = 32, slices = 64;
	float nearT = 0.25f, farT = 8.0f;   // view depth of slice 0's front and the last slice's back
	int count() const { return cols * rows * slices; }
	int index( int x, int y, int k ) const { return ( k * rows + y ) * cols + x; }
};

//! the exponential slice law: view depth at slice coordinate k (k = 0 front of slice 0). MIRROR cell_volair.frag :1254
inline float sliceDepth( const Grid & g, float k )
{
	return g.nearT * std::exp( std::log( g.farT / g.nearT ) * k / float( g.slices ) );
}

//! the view ray through column coordinate (fx, fy) in [0, cols] x [0, rows], scaled so its forward part is 1 (t = depth)
inline V3 columnDir( const Camera & c, const Grid & g, float fx, float fy )
{
	const float nx = fx / float( g.cols ) * 2.0f - 1.0f, ny = fy / float( g.rows ) * 2.0f - 1.0f;
	return c.fwd + c.right * ( nx * c.tanX ) + c.up * ( ny * c.tanY );
}

/*! The sample point of froxel (x, y, k) for a jitter u in [0, 1)^3: x, y across the column, depth LINEAR inside the slice
 *  (the same per-froxel mean the old 4-midpoint stretch estimates; fog_grid.md 2.6 G6). */
inline V3 froxelPoint( const Camera & c, const Grid & g, int x, int y, int k, V3 u )
{
	const float tA = sliceDepth( g, float( k ) ), tB = sliceDepth( g, float( k + 1 ) );
	const float t = tA + ( tB - tA ) * u.z;
	return c.pos + columnDir( c, g, float( x ) + u.x, float( y ) + u.y ) * t;
}

//! froxel centre (slice middle on the LOG law, the reprojection's point; cell_volair.frag :1314-1325)
inline V3 froxelCentre( const Camera & c, const Grid & g, int x, int y, int k )
{
	return c.pos + columnDir( c, g, float( x ) + 0.5f, float( y ) + 0.5f ) * sliceDepth( g, float( k ) + 0.5f );
}

//! a world point -> continuous froxel coordinates of camera c; false behind the camera
inline bool toFroxel( const Camera & c, const Grid & g, V3 P, float & fx, float & fy, float & fk )
{
	const V3 v = P - c.pos;
	const float z = rtddgi::dot( v, c.fwd );
	if ( !( z > 1e-6f ) )
		return false;
	fx = ( rtddgi::dot( v, c.right ) / ( z * c.tanX ) * 0.5f + 0.5f ) * float( g.cols );
	fy = ( rtddgi::dot( v, c.up ) / ( z * c.tanY ) * 0.5f + 0.5f ) * float( g.rows );
	fk = std::log( z / g.nearT ) / std::log( g.farT / g.nearT ) * float( g.slices );
	return true;
}

// ------------------------------------------------------------------ the lamp, the medium, the scene
struct Lamp
{
	V3 pos;
	float radius = 5.0f, intensity = 1.0f;
	float bias = 0.0f, scale = 1.0f, expo = 1.0f;   // the game's radial curve (lightRadial)
	V3 spotDir = V3( 0, 0, -1 );
	float cosOuter = -2.0f, cone = 1.0f;            // cosOuter < -1: omni
	bool shadow = false;                            // LIGH flags 0x400 | 0x800 | 0x1000 (cellpick.cpp; t4.y > 0.5)
	bool flicker = false;                           // cellview flicker: the fresh term, never blended
	bool mover = false;                             // a placed light that moves (atlas redraws it): position hashed
};

struct Medium
{
	float sigma = 0.05f;   // extinction to the lamp, per unit
	float g = 0.3f;        // HG asymmetry
};

struct Box
{
	V3 lo, hi;
};

//! segment P -> Lp against axis-aligned boxes (slab test, open at both ends)
struct Scene
{
	std::vector<Box> blockers;
	bool blocked( V3 P, V3 Lp ) const
	{
		const V3 d = Lp - P;
		for ( const Box & b : blockers ) {
			float t0 = 1e-5f, t1 = 1.0f - 1e-5f;
			bool hit = true;
			for ( int a = 0; a < 3 && hit; a++ ) {
				if ( std::fabs( d[a] ) < 1e-12f ) {
					if ( P[a] < b.lo[a] || P[a] > b.hi[a] )
						hit = false;
					continue;
				}
				float ta = ( b.lo[a] - P[a] ) / d[a], tb = ( b.hi[a] - P[a] ) / d[a];
				if ( ta > tb )
					std::swap( ta, tb );
				t0 = std::max( t0, ta );
				t1 = std::min( t1, tb );
				if ( t0 > t1 )
					hit = false;
			}
			if ( hit )
				return true;
		}
		return false;
	}
};

//! pi x Henyey-Greenstein (the volPhasePi convention: an isotropic medium gives 1/4)
inline float phasePi( float c, float g )
{
	const float d = 1.0f + g * g - 2.0f * g * c;
	return ( 1.0f - g * g ) / ( 4.0f * d * std::sqrt( d ) );
}

/*! The lamp's in-scatter per unit sigma_s at P before visibility (cellLightE x T x phase): 0 outside the sphere.
 *  dW = the view ray's unit direction. MIRROR cell_volair.frag :984-993 (one sample). */
inline float lampTerm( const Lamp & l, V3 P, V3 dW, const Medium & m )
{
	const V3 to = l.pos - P;
	const float d = rtddgi::length( to );
	if ( d >= l.radius || d < 0.001f || l.intensity == 0.0f )
		return 0.0f;
	const V3 L = to * ( 1.0f / d );
	float e = l.intensity * rtddgi::lightRadial( d, l.radius, l.bias, l.scale, l.expo );
	if ( l.cosOuter >= -1.0f )
		e *= rtddgi::spotCone( -rtddgi::dot( L, l.spotDir ), l.cosOuter, l.cone );
	return e * std::exp( -m.sigma * d ) * phasePi( rtddgi::dot( L, dW ), m.g );
}

//! part 22's visibility rule (fog_grid.md 2.3): a shadow LIGH takes its shadow, a non-shadow lamp V = 1
inline float visibility( const Lamp & l, V3 P, const Scene & s, const Red & r )
{
	const bool wants = l.shadow ? !r.noshadow : r.nsatlas;
	if ( !wants )
		return 1.0f;
	return s.blocked( P, l.pos ) ? 0.0f : 1.0f;
}

struct Fresh
{
	float steady = 0.0f, flicker = 0.0f;
};

//! the cluster's lamps at one point; flicker lamps into their own term unless red blendflicker
inline Fresh injectPoint( const std::vector<Lamp> & lamps, const std::vector<int> & list, V3 P, V3 dW, const Scene & s,
                          const Medium & m, const Red & r )
{
	Fresh f;
	for ( int i : list ) {
		const Lamp & l = lamps[i];
		float j = lampTerm( l, P, dW, m );
		if ( j == 0.0f )
			continue;
		j *= visibility( l, P, s, r );
		if ( l.flicker && !r.blendflicker )
			f.flicker += j;
		else
			f.steady += j;
	}
	return f;
}

/*! MODULES1 R5A-4 (bungo b60 11-10, Memory Den: "overpowered light rays striking the ground every once a while"): a lamp
 *  much smaller than a deep froxel was met by the froxel's one sample point only now and then, and a hit carried its
 *  whole in-scatter, 1 / (its share of the slice) x the mean, which the history's EMA (a = 0.1) held for ~10 frames: a
 *  flash. Each lamp now takes the same jitter u.z on its own chord: the stretch of the sample's ray C + D t inside its
 *  sphere and the slice [tA, tB], weighted by the stretch's share of the slice. Unbiased (E = 1 / (tB - tA) x the
 *  integral over the stretch), and a lamp the ray crosses is never missed in depth. Red nochord: the shared point
 *  (injectPoint at C + D (tA + (tB - tA) u.z)). MIRROR cell_volair.frag airLampVolStage */
inline Fresh injectRay( const std::vector<Lamp> & lamps, const std::vector<int> & list, V3 C, V3 D, float tA, float tB, float uz,
                        const Scene & s, const Medium & m, const Red & r )
{
	const V3 Pp = C + D * ( tA + ( tB - tA ) * uz );
	const V3 dW = rtddgi::normalize( Pp - C );
	if ( r.nochord )
		return injectPoint( lamps, list, Pp, dW, s, m, r );
	Fresh f;
	const float qa = rtddgi::dot( D, D );
	for ( int i : list ) {
		const Lamp & l = lamps[i];
		const V3 mm = C - l.pos;
		const float qb = rtddgi::dot( D, mm ), qc = rtddgi::dot( mm, mm ) - l.radius * l.radius;
		const float disc = qb * qb - qa * qc;
		if ( disc <= 0.0f || qa <= 0.0f )
			continue;
		const float sq = std::sqrt( disc );
		const float c0 = std::max( ( -qb - sq ) / qa, tA ), c1 = std::min( ( -qb + sq ) / qa, tB );
		if ( c1 <= c0 )
			continue;
		const V3 P = C + D * ( c0 + ( c1 - c0 ) * uz );
		float j = lampTerm( l, P, dW, m );
		if ( j == 0.0f )
			continue;
		j *= ( c1 - c0 ) / std::max( tB - tA, 1e-6f ) * visibility( l, P, s, r );
		if ( l.flicker && !r.blendflicker )
			f.flicker += j;
		else
			f.steady += j;
	}
	return f;
}

// ------------------------------------------------------------------ the mask
struct Mask
{
	std::vector<uint8_t> v;   // T slices of H rows of W, x fastest
	int W = 128, H = 128, T = 64;
	bool load( const std::string & path )
	{
		std::ifstream f( path, std::ios::binary );
		v.assign( size_t( W ) * H * T, 0 );
		f.read( reinterpret_cast<char *>( v.data() ), std::streamsize( v.size() ) );
		return bool( f ) && f.gcount() == std::streamsize( v.size() );
	}
	float at( int x, int y, int t ) const
	{
		x &= W - 1; y &= H - 1; t &= T - 1;
		return ( float( v[( size_t( t ) * H + y ) * W + x] ) + 0.5f ) / 256.0f;
	}
};

inline uint32_t mix32( uint32_t h )
{
	h ^= h >> 16; h *= 0x7feb352dU; h ^= h >> 15; h *= 0x846ca68bU; h ^= h >> 16;
	return h;
}

/*! The jitter of froxel (x, y, layer) at frame `frame`, sample s (0 normally; 0..3 on a history miss). Part 1's rule:
 *  one z step a frame; Part 2's rule: further values per pixel from fixed spatial offsets. Each slice of a column takes
 *  its own offset (5, 7) x layer; the three axes take (37, 71) x c; the miss samples (17, 43) x s (tried: the pixel's
 *  own time axis, frame + 16 s: G3 at 8 frames 0.835 vs 0.810, G7 0.0339 vs 0.0334, so not taken). Red white: a seeded
 *  hash (white noise). MIRROR cell_volair.frag airLampJitter */
inline V3 maskPoint( const Mask & m, int x, int y, int layer, int frame, int s, const Red & r )
{
	V3 u;
	for ( int c = 0; c < 3; c++ ) {
		if ( r.white ) {
			const uint32_t h = mix32( mix32( mix32( uint32_t( x ) * 73856093U ^ uint32_t( y ) * 19349663U ^ uint32_t( layer ) * 83492791U )
			                                 ^ uint32_t( frame ) * 2654435761U ) ^ uint32_t( s * 3 + c + 1 ) * 2246822519U );
			u[c] = ( float( h >> 8 ) + 0.5f ) / 16777216.0f;
		} else
			u[c] = m.at( x + 5 * layer + 37 * c + 17 * s, y + 7 * layer + 71 * c + 43 * s, frame );
	}
	return u;
}

// ------------------------------------------------------------------ history helpers
inline float sanitize( float x, const Red & r )
{
	if ( r.nonan )
		return x;
	if ( !std::isfinite( x ) )
		return 0.0f;
	return std::min( std::max( x, 0.0f ), kHalfMax );
}

/*! One cluster's light-set hash: per lamp in its list, mix(index + 1, steady intensity bits) (the set part) + for a
 *  mover mix(its quantised position, index) (the mover part). Flicker lamps enter by index only: their term is fresh. */
inline uint32_t clusterHash( const std::vector<Lamp> & lamps, const std::vector<int> & list, const Red & r )
{
	uint32_t h = 0;
	for ( int i : list ) {
		const Lamp & l = lamps[i];
		if ( !r.nosethash ) {
			uint32_t ib = 0;   // a steady lamp's intensity bits (a dimmer, a switch); a flicker lamp's are left out
			if ( !l.flicker )
				std::memcpy( &ib, &l.intensity, 4 );
			h += mix32( uint32_t( i + 1 ) * 0x9E3779B9U ^ ib );
		}
		if ( l.mover && !r.nomovehash ) {
			const uint32_t qx = uint32_t( int32_t( std::floor( l.pos.x * 64.0f ) ) ), qy = uint32_t( int32_t( std::floor( l.pos.y * 64.0f ) ) ),
			               qz = uint32_t( int32_t( std::floor( l.pos.z * 64.0f ) ) );
			h += mix32( mix32( mix32( qx ^ uint32_t( i + 1 ) ) ^ qy ) ^ qz );
		}
	}
	return h;
}

/*! The old path (red pixel): cell_volair.frag airRest :966-1005, the column-centre ray through slice k, each lamp's
 *  stretch inside its sphere sampled at 4 midpoints, weighted by its share of the slice; the visibility (the atlas,
 *  airLeakLightK) taken ONCE at the froxel middle, for every lamp (shadow flag ignored). No history. */
inline float oldPath( const Camera & c, const Grid & g, int x, int y, int k, const std::vector<Lamp> & lamps,
                      const std::vector<int> & list, const Scene & s, const Medium & m )
{
	const V3 D = columnDir( c, g, float( x ) + 0.5f, float( y ) + 0.5f );
	const V3 dW = rtddgi::normalize( D );
	const float sA = sliceDepth( g, float( k ) ), sB = sliceDepth( g, float( k + 1 ) );
	const V3 Pmid = c.pos + D * ( 0.5f * ( sA + sB ) );
	float J = 0.0f;
	for ( int i : list ) {
		const Lamp & l = lamps[i];
		const V3 mm = c.pos - l.pos;
		const float qa = rtddgi::dot( D, D ), qb = rtddgi::dot( D, mm ), qc = rtddgi::dot( mm, mm ) - l.radius * l.radius;
		const float disc = qb * qb - qa * qc;
		if ( disc <= 0.0f || qa <= 0.0f )
			continue;
		const float sq = std::sqrt( disc );
		const float s0 = std::max( ( -qb - sq ) / qa, sA ), s1 = std::min( ( -qb + sq ) / qa, sB );
		if ( s1 <= s0 )
			continue;
		float Ji = 0.0f;
		for ( int q = 0; q < 4; q++ ) {
			const V3 Pk = c.pos + D * ( s0 + ( s1 - s0 ) * ( ( float( q ) + 0.5f ) * 0.25f ) );
			Ji += lampTerm( l, Pk, dW, m );
		}
		if ( Ji > 0.0f && s.blocked( Pmid, l.pos ) )   // airLeakLightK( i, P, lamp ): every lamp, NS included
			Ji = 0.0f;
		J += Ji * ( 0.25f * ( s1 - s0 ) / std::max( sB - sA, 1e-6f ) );
	}
	return J;
}

// ------------------------------------------------------------------ the volume, frame by frame
struct FrameIn
{
	Camera cam;
	bool cut = false;                 // the renderer knows: a teleport, a cell change, the first frame
	std::vector<Lamp> lamps;
	Scene scene;
	Medium medium;
	std::vector<uint8_t> skip;        // per froxel: depth-skipped (behind opaque) this frame; empty = none
	int frame = 0;
};

struct Stats
{
	int rejCut = 0, rejFrustum = 0, rejSkip = 0, rejHash = 0, rejNan = 0, kept = 0, skipped = 0;
};

class LampVolume
{
public:
	Grid g;
	Red red;
	const Mask * mask = nullptr;
	std::vector<float> out, hist, histN, steadyNow, flickerNow;
	std::vector<uint8_t> valid, samplesUsed, keptNow;   // valid: history usable (0 = skipped / never written); keptNow: blended this frame
	//! histN: the samples the history holds (reprojected like the value, capped at 64). The blend is the history-length
	//! ramp a = max(a, 1 / (N + 1)) (SVGF's rule): an exact running mean until 1/(N+1) falls to the briefed a, then the
	//! briefed EMA. Added after run 3: fixed a = 0.1 lets the first estimate keep 0.9^7 = 48 % of the weight after 8
	//! frames, so G3 at 8 frames read 0.976 (mask and white alike); with the ramp 0.370. Red noramp
	std::vector<uint32_t> hash, prevHash;
	std::vector<std::vector<int>> lists;
	Camera prevCam;
	bool havePrev = false;
	Stats st;

	int ccols() const { return g.cols / kClusterXY; }
	int crows() const { return g.rows / kClusterXY; }
	int cslices() const { return g.slices / kClusterZ; }
	int clusterOf( int x, int y, int k ) const { return ( ( k / kClusterZ ) * crows() + y / kClusterXY ) * ccols() + x / kClusterXY; }

	//! the cluster lists: every lamp (intensity != 0) whose sphere meets the cluster's box (the frustum chunk's 8 corners)
	void buildClusters( const FrameIn & in )
	{
		const int nc = ccols() * crows() * cslices();
		lists.assign( nc, {} );
		hash.assign( nc, 0 );
		for ( int cz = 0; cz < cslices(); cz++ )
			for ( int cy = 0; cy < crows(); cy++ )
				for ( int cx = 0; cx < ccols(); cx++ ) {
					V3 lo( 1e30f, 1e30f, 1e30f ), hi( -1e30f, -1e30f, -1e30f );
					for ( int q = 0; q < 8; q++ ) {
						const float fx = float( ( cx + ( q & 1 ) ) * kClusterXY ), fy = float( ( cy + ( ( q >> 1 ) & 1 ) ) * kClusterXY );
						const float t = sliceDepth( g, float( ( cz + ( q >> 2 ) ) * kClusterZ ) );
						const V3 p = in.cam.pos + columnDir( in.cam, g, fx, fy ) * t;
						for ( int a = 0; a < 3; a++ ) {
							lo[a] = std::min( lo[a], p[a] );
							hi[a] = std::max( hi[a], p[a] );
						}
					}
					const int ci = ( cz * crows() + cy ) * ccols() + cx;
					for ( int i = 0; i < int( in.lamps.size() ); i++ ) {
						const Lamp & l = in.lamps[i];
						if ( l.intensity == 0.0f )
							continue;
						float d2 = 0.0f;
						for ( int a = 0; a < 3; a++ ) {
							const float e = std::max( std::max( lo[a] - l.pos[a], 0.0f ), l.pos[a] - hi[a] );
							d2 += e * e;
						}
						if ( d2 < l.radius * l.radius )
							lists[ci].push_back( i );
					}
					hash[ci] = clusterHash( in.lamps, lists[ci], red );
				}
	}

	/*! History at froxel (x, y, k) of the current camera: the centre reprojected into the previous grid, trilinear.
	 *  Returns false (reject) and the rule that fired. MIRROR cell_volair.frag airLampHist */
	bool history( const FrameIn & in, int x, int y, int k, float & h, int & why, int * prevCluster = nullptr, float * hn = nullptr ) const
	{
		why = 0;
		if ( !havePrev || ( in.cut && !red.nofrustum ) ) {
			why = 1;
			return false;
		}
		float fx, fy, fk;
		const V3 Pc = froxelCentre( in.cam, g, x, y, k );
		if ( !toFroxel( prevCam, g, Pc, fx, fy, fk ) ) {
			if ( !red.nofrustum ) {
				why = 2;
				return false;
			}
			fx = float( x ) + 0.5f; fy = float( y ) + 0.5f; fk = float( k ) + 0.5f;
		}
		if ( prevCluster ) {   // the cluster the history comes from: its previous hash is the one rule 3 compares
			auto cl = []( float q, int n ) { return std::min( std::max( int( std::floor( q ) ), 0 ), n - 1 ); };
			*prevCluster = clusterOf( cl( fx, g.cols ), cl( fy, g.rows ), cl( fk, g.slices ) );
		}
		const float gx = fx - 0.5f, gy = fy - 0.5f, gk = fk - 0.5f;
		const int x0 = int( std::floor( gx ) ), y0 = int( std::floor( gy ) ), k0 = int( std::floor( gk ) );
		const float wx = gx - float( x0 ), wy = gy - float( y0 ), wk = gk - float( k0 );
		float acc = 0.0f, accN = 0.0f, wsum = 0.0f;
		for ( int q = 0; q < 8; q++ ) {
			const int ix = x0 + ( q & 1 ), iy = y0 + ( ( q >> 1 ) & 1 ), ik = k0 + ( q >> 2 );
			const float w = ( q & 1 ? wx : 1.0f - wx ) * ( ( q >> 1 ) & 1 ? wy : 1.0f - wy ) * ( q >> 2 ? wk : 1.0f - wk );
			if ( w < 1e-6f )
				continue;
			if ( ix < 0 || iy < 0 || ik < 0 || ix >= g.cols || iy >= g.rows || ik >= g.slices ) {
				if ( !red.nofrustum ) {
					why = 2;
					return false;
				}
				continue;
			}
			const int j = g.index( ix, iy, ik );
			if ( !valid[j] && !red.noskip ) {
				why = 3;
				return false;
			}
			acc += hist[j] * w;
			if ( hn )
				accN += histN[j] * w;
			wsum += w;
		}
		if ( wsum <= 0.0f ) {
			why = 2;
			return false;
		}
		h = acc / wsum;
		if ( hn )
			*hn = accN / wsum;
		if ( !std::isfinite( h ) && !red.nonan ) {
			why = 5;
			return false;
		}
		return true;
	}

	//! one froxel's fresh estimate with n samples (the mean)
	Fresh fresh( const FrameIn & in, int x, int y, int k, int n ) const
	{
		const int ci = clusterOf( x, y, k );
		Fresh f;
		for ( int s = 0; s < n; s++ ) {
			const V3 u = maskPoint( *mask, x, y, k, in.frame, s, red );
			const V3 D = columnDir( in.cam, g, float( x ) + u.x, float( y ) + u.y );
			const Fresh a = injectRay( in.lamps, lists[ci], in.cam.pos, D, sliceDepth( g, float( k ) ), sliceDepth( g, float( k + 1 ) ), u.z,
			                           in.scene, in.medium, red );
			f.steady += a.steady;
			f.flicker += a.flicker;
		}
		f.steady /= float( n );
		f.flicker /= float( n );
		return f;
	}

	void step( const FrameIn & in )
	{
		const int N = g.count();
		if ( int( hist.size() ) != N ) {
			hist.assign( N, 0.0f );
			histN.assign( N, 0.0f );
			valid.assign( N, 0 );
		}
		out.assign( N, 0.0f );
		steadyNow.assign( N, 0.0f );
		flickerNow.assign( N, 0.0f );
		samplesUsed.assign( N, 0 );
		keptNow.assign( N, 0 );
		buildClusters( in );
		st = Stats();
		const bool moving = havePrev && !( in.cam == prevCam );
		const float a = moving ? kAMoving : kAStill;
		std::vector<float> newHist( N, 0.0f ), newN( N, 0.0f );
		std::vector<uint8_t> newValid( N, 0 );
		for ( int k = 0; k < g.slices; k++ )
			for ( int y = 0; y < g.rows; y++ )
				for ( int x = 0; x < g.cols; x++ ) {
					const int j = g.index( x, y, k );
					if ( !in.skip.empty() && in.skip[j] ) {   // stage 0: behind opaque, (0, invalid)
						st.skipped++;
						continue;
					}
					if ( red.pixel ) {
						const int ci = clusterOf( x, y, k );
						out[j] = oldPath( in.cam, g, x, y, k, in.lamps, lists[ci], in.scene, in.medium );
						steadyNow[j] = out[j];
						continue;
					}
					float h = 0.0f, hn = 0.0f;
					int why = 0, pc = -1;
					bool keep = history( in, x, y, k, h, why, &pc, &hn );
					const int ci = clusterOf( x, y, k );
					if ( keep && hash[ci] != prevHash[pc] ) {   // rule 3: this cluster's set now vs the history's cluster then
						keep = false;
						why = 4;
					}
					Fresh f;
					float s;
					if ( keep ) {
						f = fresh( in, x, y, k, 1 );
						const float ak = red.noramp ? a : std::max( a, 1.0f / ( hn + 1.0f ) );
						s = h + ak * ( f.steady - h );
						newN[j] = std::min( hn + 1.0f, 64.0f );
						samplesUsed[j] = 1;
						keptNow[j] = 1;
						st.kept++;
					} else {
						const int n = red.onemiss ? 1 : kMissSamples;
						f = fresh( in, x, y, k, n );
						s = f.steady;
						newN[j] = float( n );
						samplesUsed[j] = uint8_t( n );
						( why == 1 ? st.rejCut : why == 2 ? st.rejFrustum : why == 3 ? st.rejSkip : why == 4 ? st.rejHash : st.rejNan )++;
					}
					s = sanitize( s, red );
					const float fl = sanitize( f.flicker, red );
					newHist[j] = s;
					newValid[j] = 1;
					steadyNow[j] = s;
					flickerNow[j] = fl;
					out[j] = red.nonan ? s + fl : std::min( s + fl, kHalfMax );
				}
		hist.swap( newHist );
		histN.swap( newN );
		valid.swap( newValid );
		prevHash = hash;
		prevCam = in.cam;
		havePrev = true;
	}
};

